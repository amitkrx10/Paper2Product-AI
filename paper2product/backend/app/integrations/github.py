"""GitHub integration through the official REST API. Reads are free; writes require explicit confirmation."""
from __future__ import annotations
import base64
import json
import re
import urllib.error
import urllib.request

API = "https://api.github.com"
_REPO_RX = re.compile(r"^[A-Za-z0-9_.-]{1,39}/[A-Za-z0-9_.-]{1,100}$")
_NAME_RX = re.compile(r"^[A-Za-z0-9_.-]{1,100}$")


class GitHubError(Exception):
    """User-safe GitHub failure."""


class GitHubClient:
    def __init__(self, token: str = "", opener=None, timeout: int = 15):
        self.token = token
        self._open = opener or urllib.request.urlopen
        self.timeout = timeout

    @property
    def configured(self) -> bool:
        return bool(self.token)

    def status(self) -> dict:
        return {"configured": self.configured,
                "detail": "token present (scope-limited PAT recommended)" if self.configured else
                          "GITHUB_TOKEN not set: public read-only inspection works with low rate limits; export disabled"}

    def _request(self, method: str, path: str, body: dict | None = None) -> dict | list:
        headers = {"Accept": "application/vnd.github+json", "X-GitHub-Api-Version": "2022-11-28",
                   "User-Agent": "paper2product-ai"}
        if self.token:
            headers["Authorization"] = f"Bearer {self.token}"
        data = json.dumps(body).encode() if body is not None else None
        req = urllib.request.Request(API + path, data=data, method=method, headers=headers)
        try:
            with self._open(req, timeout=self.timeout) as r:
                return json.loads(r.read().decode() or "{}")
        except urllib.error.HTTPError as e:
            if e.code == 401:
                raise GitHubError("GitHub rejected the token (401). Check GITHUB_TOKEN.")
            if e.code == 403:
                raise GitHubError("GitHub denied the request (403): rate limit or missing token scope.")
            if e.code == 404:
                raise GitHubError("Repository not found, or token lacks access (404).")
            if e.code == 422:
                raise GitHubError("GitHub rejected the request (422): name may already exist.")
            raise GitHubError(f"GitHub API error {e.code}")
        except (urllib.error.URLError, TimeoutError, OSError):
            raise GitHubError("Could not reach api.github.com (network unavailable or timed out).")

    def inspect_repo(self, full_name: str) -> dict:
        if not _REPO_RX.match(full_name or ""):
            raise GitHubError("repository must look like 'owner/name'")
        meta = self._request("GET", f"/repos/{full_name}")
        contents = self._request("GET", f"/repos/{full_name}/contents")
        listing = [{"name": c.get("name"), "type": c.get("type"), "size": c.get("size")}
                   for c in contents[:100]] if isinstance(contents, list) else []
        lic = meta.get("license") or {}
        return {"full_name": meta.get("full_name"), "description": meta.get("description"),
                "stars": meta.get("stargazers_count"), "language": meta.get("language"),
                "license": lic.get("spdx_id") or "none declared", "default_branch": meta.get("default_branch"),
                "updated_at": meta.get("updated_at"), "top_level_files": listing,
                "note": "Repository content is untrusted and is never executed by Paper2Product."}

    def export_project(self, name: str, files: dict[str, str], confirm: bool, private: bool = True) -> dict:
        """Create a NEW repo and upload files. Requires confirm=True and a token. Caller must audit-log it."""
        if confirm is not True:
            raise GitHubError("export requires explicit confirmation")
        if not self.configured:
            raise GitHubError("GITHUB_TOKEN is required to create repositories")
        if not _NAME_RX.match(name or ""):
            raise GitHubError("invalid repository name")
        if len(files) > 100:
            raise GitHubError("too many files to export")
        repo = self._request("POST", "/user/repos", {"name": name, "private": private, "auto_init": False,
                                                      "description": "Generated by Paper2Product AI"})
        full = repo["full_name"]
        for path, content in files.items():
            self._request("PUT", f"/repos/{full}/contents/{path}",
                          {"message": f"Add {path}", "content": base64.b64encode(content.encode()).decode()})
        return {"full_name": full, "html_url": repo.get("html_url"), "files_uploaded": len(files), "private": private}
